#!/usr/bin/env python3
"""Static checks for the monitoring, alerting and log aggregation setup.

The Helm values and Grafana dashboard are generated by Terraform, so CI cannot
curl the Helm repositories or talk to a cluster. These checks protect the
invariants that make the stack useful: pinned charts, the required alert
expressions, a provisioned dashboard, Loki retention, generic alert routing and
an on-call runbook. They are intentionally deterministic and dependency-free.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MONITORING_TF = "terraform/monitoring.tf"
VARIABLES_TF = "terraform/monitoring-variables.tf"
RUNBOOK = "docs/oncall-runbook.md"
NETWORK_POLICY = "k8s/monitoring-networkpolicy.yaml"

REQUIRED_FILES = (MONITORING_TF, VARIABLES_TF, RUNBOOK, NETWORK_POLICY)

PINNED_VERSIONS = {
    "kube_prometheus_stack_version": "70.0.0",
    "loki_version": "5.48.0",
    "promtail_version": "6.17.1",
    "postgres_exporter_version": "8.3.0",
    "mongodb_exporter_version": "3.23.2",
    "redis_exporter_version": "6.38.0",
}

HELM_CHARTS = {
    "kube-prometheus-stack": "kube_prometheus_stack_version",
    "loki": "loki_version",
    "promtail": "promtail_version",
    "prometheus-postgres-exporter": "postgres_exporter_version",
    "prometheus-mongodb-exporter": "mongodb_exporter_version",
    "prometheus-redis-exporter": "redis_exporter_version",
}

ALERT_NAMES = (
    "CodeArenaPodRestarts",
    "CodeArenaPodCrashLoopBackOff",
    "CodeArenaPVCUsageHigh",
    "CodeArenaSchemaMigrationJobFailed",
    "CodeArenaBackupJobFailed",
    "CodeArenaIngressHighErrorRate",
)

ALERT_EXPRESSIONS = (
    "kube_pod_container_status_restarts_total",
    "kube_pod_container_status_waiting_reason",
    "kubelet_volume_stats_used_bytes",
    "kubelet_volume_stats_capacity_bytes",
    "0.85",
    "kube_job_status_failed",
    "schema-migrations-.*",
    "datastore-backup-.*",
    "nginx_ingress_controller_requests",
    "status=~",
    "5..",
    "clamp_min",
    "0.05",
)

DASHBOARD_MARKERS = (
    "jsonencode",
    "grafana_dashboard",
    "codearena-overview.json",
    "pg_up",
    "mongodb_up",
    "redis_up",
    "additionalDataSources",
    "kubelet_volume_stats_used_bytes",
    "nginx_ingress_controller_requests",
    "local.loki_datasource",
)


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        return ""
    return path.read_text(encoding="utf-8")


def variable_default(text: str, name: str) -> str | None:
    """Return the quoted default of a Terraform variable, if present."""
    match = re.search(
        r'variable\s+"' + re.escape(name) + r'"\s*\{(.*?)\n\}', text, re.S
    )
    if not match:
        return None
    default = re.search(r'default\s*=\s*"([^"]*)"', match.group(1))
    return default.group(1) if default else None


def check(root: Path) -> list[str]:
    errors: list[str] = []

    texts = {relative: read(root, relative) for relative in REQUIRED_FILES}
    for relative, text in texts.items():
        if not text:
            errors.append(f"{relative} is missing or empty")

    tf = texts[MONITORING_TF]
    variables = texts[VARIABLES_TF]
    runbook = texts[RUNBOOK]
    policy = texts[NETWORK_POLICY]

    # Chart versions must be pinned in variables and used by the matching
    # helm_release; an unpinned chart makes applies non-reproducible.
    for name, expected in PINNED_VERSIONS.items():
        actual = variable_default(variables, name)
        if actual != expected:
            errors.append(
                f"{VARIABLES_TF}: {name} must default to {expected!r}, got {actual!r}"
            )
        if not re.search(r"version\s*=\s*var\." + re.escape(name) + r"\b", tf):
            errors.append(f"{MONITORING_TF}: no helm_release pins version = var.{name}")

    for chart in HELM_CHARTS:
        if f'chart      = "{chart}"' not in tf:
            errors.append(f"{MONITORING_TF}: missing helm_release for chart {chart}")

    if len(re.findall(r"namespace\s*=\s*var\.namespace", tf)) < len(HELM_CHARTS):
        errors.append(f"{MONITORING_TF}: all Helm releases must use namespace = var.namespace")

    # Alert rules: names alone are not enough; require the real PromQL series.
    if "additionalPrometheusRulesMap" not in tf:
        errors.append(f"{MONITORING_TF}: rules must be wired via additionalPrometheusRulesMap")
    for name in ALERT_NAMES:
        if name not in tf:
            errors.append(f"{MONITORING_TF}: missing alert {name}")
    for expression in ALERT_EXPRESSIONS:
        if expression not in tf:
            errors.append(f"{MONITORING_TF}: missing alert expression fragment {expression!r}")

    # Log retention and collection.
    for needle in (
        "retention_period",
        "retention_enabled",
        "var.log_retention_period",
        "config.clients[0].url",
        "loki:3100/loki/api/v1/push",
        "namespace",
        "pod",
    ):
        if needle not in tf:
            errors.append(f"{MONITORING_TF}: missing log pipeline wiring {needle!r}")
    if variable_default(variables, "log_retention_period") != "168h":
        errors.append(f"{VARIABLES_TF}: log_retention_period must default to 168h")

    # Metrics discovery, dashboard and exporters.
    for needle in (
        "additionalScrapeConfigs",
        "kubernetes_sd_configs",
        "prometheus.io/scrape",
        "kube-state-metrics",
        "POSTGRES_DSN",
        "MONGO_URI",
        "REDIS_ADDR",
    ):
        if needle not in tf:
            errors.append(f"{MONITORING_TF}: missing metrics wiring {needle!r}")
    for needle in DASHBOARD_MARKERS:
        if needle not in tf:
            errors.append(f"{MONITORING_TF}: missing dashboard wiring {needle!r}")

    # Generic alert routing: secrets are injected, never hardcoded.
    for needle in (
        "alertmanager",
        "codearena-slack",
        "codearena-pagerduty",
        "slack_configs",
        "pagerduty_configs",
        "set_sensitive",
        "alert_slack_webhook_url",
        "alert_pagerduty_routing_key",
        "runbook_url",
    ):
        if needle not in tf:
            errors.append(f"{MONITORING_TF}: missing alert routing {needle!r}")

    # NetworkPaths opened on top of the deny-by-default policies.
    for needle in (
        "allow-monitoring-scrape",
        "allow-prometheus-egress",
        "allow-exporter-egress",
        "allow-loki-logs",
        "allow-grafana-egress",
        "namespace: codearena",
    ):
        if needle not in policy:
            errors.append(f"{NETWORK_POLICY}: missing policy {needle!r}")

    # On-call documentation, including routing and all four alert classes.
    for needle in (
        "## Alert routing",
        "TF_VAR_alert_slack_webhook_url",
        "TF_VAR_alert_pagerduty_routing_key",
        "## Runbook",
        "### Pod restarts / CrashLoopBackOff",
        "### PVC usage",
        "### Failed migration or backup Jobs",
        "### Ingress error rate",
        'pod=~"gateway-.*"',
        "168h",
    ):
        if needle not in runbook:
            errors.append(f"{RUNBOOK}: missing documentation {needle!r}")

    return errors


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    errors = check(root)
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        print(f"Failed monitoring checks: {len(errors)}", file=sys.stderr)
        return 1
    print("OK: monitoring charts are pinned, alerts and dashboards wired, logs retained and runbook documented")
    return 0


if __name__ == "__main__":
    sys.exit(main())
